#!/usr/bin/env python3
"""Build RSS feeds for CKUT show pages that have no working feed of their own.

CKUT's playlist pages are generated by KenzoDB and advertise two feeds
(/playlistfeed/<SHOW>.xml and /archivefeed/mp3/<SHOW>.xml) that both return
404. This script scrapes the same HTML a browser would see and writes:

  feed-<show>.xml          episode list + full tracklist in the description
  podcast-<show>.xml       the same, plus <enclosure> pointing at the
                           station's own MP3 archive (nothing is rehosted)

Run:  FEED_BASE_URL=https://user.github.io/ckut-feeds python scrape.py
"""

from __future__ import annotations

import datetime as dt
import email.utils
import json
import os
import re
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from zoneinfo import ZoneInfo

import requests
from bs4 import BeautifulSoup

ROOT = Path(__file__).resolve().parent
CACHE_DIR = ROOT / "cache"
TRACKLIST_CACHE = CACHE_DIR / "tracklists.json"
AUDIO_CACHE = CACHE_DIR / "audio.json"

BASE = "https://ckut.ca"
SHOW = os.environ.get("CKUT_SHOW", "OH")
SHOW_NAME = os.environ.get("CKUT_SHOW_NAME", "Off The Hook")
SHOW_SCHEDULE = os.environ.get("CKUT_SHOW_SCHEDULE", "Every Thursday, midnight-2am (America/Toronto)")
FEED_BASE_URL = os.environ.get("FEED_BASE_URL", "").rstrip("/")
MAX_ITEMS = int(os.environ.get("CKUT_MAX_ITEMS", "40"))
REFRESH_RECENT = int(os.environ.get("CKUT_REFRESH_RECENT", "3"))
EXTRA_YEARS = [y.strip() for y in os.environ.get("CKUT_YEARS", "").split(",") if y.strip()]
USER_AGENT = os.environ.get(
    "CKUT_USER_AGENT", "ckut-feed/1.0 (personal RSS generator; ckut.ca show playlists)"
)

TIMEOUT = 30
TZ = ZoneInfo("America/Toronto")

MONTHS = {
    "January": 1, "February": 2, "March": 3, "April": 4, "May": 5, "June": 6,
    "July": 7, "August": 8, "September": 9, "October": 10, "November": 11,
    "December": 12,
}

DATE_RE = re.compile(r"([A-Z][a-z]+) (\d{1,2}), (\d{4})")
PLAYLIST_RE = re.compile(r"/playlists/shows/(\d+)")
ARCHIVE_RE = re.compile(r"[?&]archive=(\d+)")


# ---------------------------------------------------------------- data model


@dataclass
class Episode:
    date: dt.date
    playlist_id: str | None = None
    archive_id: str | None = None
    show_id: str | None = None
    note: str = ""
    songs: list[dict[str, str]] = field(default_factory=list)
    audio: dict[str, Any] | None = None

    @property
    def key(self) -> str:
        return self.playlist_id or self.archive_id or self.date.isoformat()

    @property
    def title(self) -> str:
        return f"{SHOW_NAME} — {self.date.strftime('%B')} {self.date.day}, {self.date.year}"

    @property
    def page_url(self) -> str:
        if self.playlist_id:
            return f"{BASE}/playlists/shows/{self.playlist_id}"
        return f"{BASE}/playlists/{SHOW}"

    @property
    def audio_url(self) -> str | None:
        """Stable entry point.

        The CDN paths under archives.ckut.ca/archives/ are an evictable cache
        and start answering 404 once a file ages out, so link to the station's
        own download endpoint instead: it always resolves, even if the response
        it redirects to is a cold-cache stream.
        """
        show_id = self.show_id or self.playlist_id
        if not (self.archive_id and show_id):
            return None
        return f"{BASE}/listen.php?show={show_id}d&archive={self.archive_id}"


# ---------------------------------------------------------------------- http


def make_session() -> requests.Session:
    s = requests.Session()
    s.headers.update({"User-Agent": USER_AGENT, "Accept-Language": "en-CA,en;q=0.9"})
    return s


def fetch(session: requests.Session, url: str) -> str | None:
    try:
        r = session.get(url, timeout=TIMEOUT)
        r.raise_for_status()
        r.encoding = r.encoding or "utf-8"
        return r.text
    except requests.RequestException as exc:
        print(f"[warn] GET {url} failed: {exc}", file=sys.stderr)
        return None


# --------------------------------------------------------------------- parse


def parse_index(html: str) -> list[Episode]:
    """Every episode listed on a /playlists/<SHOW>[YYYY] archive page."""
    soup = BeautifulSoup(html, "html.parser")
    episodes: list[Episode] = []

    for li in soup.select("div.playlist-archive li"):
        text = li.get_text(" ", strip=True)
        m = DATE_RE.search(text)
        if not m:
            continue
        month, day, year = m.group(1), int(m.group(2)), int(m.group(3))
        if month not in MONTHS:
            continue
        try:
            date = dt.date(year, MONTHS[month], day)
        except ValueError:
            continue

        ep = Episode(date=date)
        link = li.find("a", href=PLAYLIST_RE)
        if link:
            ep.playlist_id = PLAYLIST_RE.search(link["href"]).group(1)

        dl = li.find("a", href=re.compile(r"listen\.php"))
        if dl:
            am = ARCHIVE_RE.search(dl["href"])
            if am:
                ep.archive_id = am.group(1)
            sm = re.search(r"[?&]show=(\d+)", dl["href"])
            if sm:
                ep.show_id = sm.group(1)

        # episodes without a published tracklist still have an archive player link
        if not ep.show_id:
            player = li.find("a", href=re.compile(r"archiveplayer\.php"))
            if player:
                sm = re.search(r"[?&]show=(\d+)", player["href"])
                if sm:
                    ep.show_id = sm.group(1)

        if "still being updated" in text.lower():
            ep.note = "Playlist still being updated."
        if not ep.playlist_id:
            ep.note = (ep.note + " No tracklist was published for this episode.").strip()

        episodes.append(ep)

    return episodes


def parse_show_page(html: str) -> list[dict[str, str]]:
    soup = BeautifulSoup(html, "html.parser")
    table = soup.select_one("#drop_table") or soup.select_one("span#songs") or soup

    def cell(tr: Any, cls: str) -> str:
        td = tr.find("td", class_=cls)
        if not td:
            return ""
        text = td.get_text(" ", strip=True).replace("\xa0", " ")
        return re.sub(r"\s+", " ", text).strip()

    songs: list[dict[str, str]] = []
    for tr in table.select("tr"):
        if not tr.find("td", class_="col_artist"):
            continue
        song = {
            "artist": cell(tr, "col_artist"),
            "track": cell(tr, "col_song_title"),
            "album": cell(tr, "col_album_title"),
            "label": cell(tr, "col_record_label"),
            "year": cell(tr, "col_year"),
            "comments": cell(tr, "col_comments"),
        }
        if song["artist"] or song["track"]:
            songs.append(song)
    return songs


def resolve_audio(session: requests.Session, ep: Episode) -> dict[str, Any] | None:
    """Follow listen.php through its redirects to the public MP3.

    The archive CDN occasionally answers a burst with an error or a chunked
    response, so try a couple of times before giving up.
    """
    show_id = ep.show_id or ep.playlist_id
    if not (ep.archive_id and show_id):
        return None
    url = f"{BASE}/listen.php?show={show_id}d&archive={ep.archive_id}"

    for attempt in range(3):
        try:
            r = session.head(url, allow_redirects=True, timeout=TIMEOUT)
            final = r.url
            length = r.headers.get("Content-Length")
            ctype = r.headers.get("Content-Type", "audio/mpeg")
            status = r.status_code
            r.close()
            if status == 405:  # HEAD not allowed
                r = session.get(url, allow_redirects=True, stream=True, timeout=TIMEOUT)
                final, length = r.url, r.headers.get("Content-Length")
                ctype, status = r.headers.get("Content-Type", ctype), r.status_code
                r.close()
        except requests.RequestException as exc:
            print(f"[warn] audio lookup failed for {url}: {exc}", file=sys.stderr)
            time.sleep(1.5 * (attempt + 1))
            continue

        if status < 400 and final.endswith(".mp3"):
            size = int(length) if length and length.isdigit() else probe_size(session, final)
            if size:
                duration = duration_from_name(final)
                if duration is None:
                    duration = int(size * 8 / 128_000)
                return {
                    "url": final,
                    "length": size,
                    "type": ctype or "audio/mpeg",
                    "duration": duration,
                }
        print(f"[warn] {url}: status={status} size=0 (attempt {attempt + 1})", file=sys.stderr)
        time.sleep(1.5 * (attempt + 1))

    return None


def probe_size(session: requests.Session, url: str) -> int:
    """Some CDN responses are chunked; a one-byte range request exposes the total."""
    try:
        r = session.get(url, headers={"Range": "bytes=0-0"}, stream=True, timeout=TIMEOUT)
        m = re.search(r"/(\d+)$", r.headers.get("Content-Range", ""))
        size = int(m.group(1)) if m else 0
        if not size:
            total = r.headers.get("Content-Length", "")
            size = int(total) if total.isdigit() else 0
        r.close()
        return size
    except requests.RequestException as exc:
        print(f"[warn] size probe failed for {url}: {exc}", file=sys.stderr)
        return 0


def duration_from_name(url: str) -> int | None:
    """...20261105.00.00.00-02.00.00.mp3 -> 7200 seconds."""
    m = re.search(r"-(\d{2})\.(\d{2})\.(\d{2})\.mp3$", url)
    if not m:
        return None
    h, mi, s = (int(g) for g in m.groups())
    return h * 3600 + mi * 60 + s


# ---------------------------------------------------------------- rss output


def cdata(html: str) -> str:
    return "<![CDATA[" + html.replace("]]>", "]]]]><![CDATA[>") + "]]>"


def esc(text: str) -> str:
    return (
        str(text)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def tracklist_html(ep: Episode) -> str:
    parts = [f'<p><a href="{esc(ep.page_url)}">Playlist on ckut.ca</a></p>']
    if ep.note:
        parts.append(f"<p><em>{esc(ep.note)}</em></p>")
    if ep.songs:
        parts.append("<ol>")
        for song in ep.songs:
            line = f"<li><strong>{esc(song['artist'] or 'Unknown')}</strong>"
            if song["track"]:
                line += f" — {esc(song['track'])}"
            extra = [esc(v) for v in (song["album"], song["year"]) if v]
            if extra:
                line += f" <em>({', '.join(extra)})</em>"
            parts.append(line + "</li>")
        parts.append("</ol>")
    elif ep.playlist_id and "still being updated" not in ep.note:
        parts.append("<p><em>No tracklist published yet.</em></p>")
    return "".join(parts)


def pub_date(ep: Episode) -> str:
    stamp = dt.datetime.combine(ep.date, dt.time(0, 0), tzinfo=TZ)
    return email.utils.format_datetime(stamp)


def artwork_url() -> str:
    """Square cover art served from the same Pages site (see README)."""
    return os.environ.get("CKUT_ARTWORK_URL", "").strip() or f"{FEED_BASE_URL}/artwork.jpg"


def build_feed(episodes: list[Episode], kind: str) -> str:
    podcast = kind == "podcast"
    self_url = f"{FEED_BASE_URL}/podcast-{SHOW.lower()}.xml" if podcast else f"{FEED_BASE_URL}/feed-{SHOW.lower()}.xml"
    channel_title = (
        f"CKUT — {SHOW_NAME} (audio archives)" if podcast else f"CKUT — {SHOW_NAME} playlists"
    )
    channel_desc = (
        f"Audio archives of {SHOW_NAME} on CKUT 90.3 FM, Montreal. {SHOW_SCHEDULE}. "
        "MP3s are served by ckut.ca."
        if podcast
        else f"Playlists for {SHOW_NAME} on CKUT 90.3 FM, Montreal. {SHOW_SCHEDULE}. "
        "Scraped from ckut.ca, whose own playlist feed returns 404."
    )

    # newest item rather than wall-clock time, so a run with no new episodes
    # produces byte-identical output and the workflow commits nothing
    now = pub_date(episodes[0]) if episodes else email.utils.format_datetime(dt.datetime.now(TZ))
    art = artwork_url()
    out: list[str] = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom"'
        + (' xmlns:itunes="http://www.itunes.com/dtds/podcast-1.0.dtd"' if podcast else "")
        + ">",
        "<channel>",
        f"<title>{esc(channel_title)}</title>",
        f"<link>{esc(BASE + '/playlists/' + SHOW)}</link>",
        f"<description>{esc(channel_desc)}</description>",
        "<language>en-ca</language>",
        f"<lastBuildDate>{now}</lastBuildDate>",
        "<ttl>60</ttl>",
        "<generator>ckut-feeds scrape.py</generator>",
        f'<atom:link href="{esc(self_url)}" rel="self" type="application/rss+xml"/>',
        f"<image><url>{esc(art)}</url><title>{esc(channel_title)}</title>"
        f"<link>{esc(BASE + '/playlists/' + SHOW)}</link></image>",
    ]
    if podcast:
        out += [
            f'<itunes:image href="{esc(art)}"/>',
            "<itunes:author>CKUT 90.3 FM</itunes:author>",
            f"<itunes:summary>{esc(channel_desc)}</itunes:summary>",
            "<itunes:explicit>false</itunes:explicit>",
            '<itunes:category text="Music"/>',
        ]

    for ep in episodes:
        guid = f"ckut:{SHOW.lower()}:archive:{ep.archive_id}" if podcast and ep.archive_id else f"ckut:{SHOW.lower()}:playlist:{ep.key}"
        out.append("<item>")
        out.append(f"<title>{esc(ep.title)}</title>")
        out.append(f"<link>{esc(ep.page_url)}</link>")
        out.append(f'<guid isPermaLink="false">{esc(guid)}</guid>')
        out.append(f"<pubDate>{pub_date(ep)}</pubDate>")
        out.append(f"<description>{cdata(tracklist_html(ep))}</description>")
        if podcast:
            out.append(f'<itunes:image href="{esc(art)}"/>')
            if ep.audio_url:
                length = ep.audio.get("length") if ep.audio else 0
                out.append(
                    f'<enclosure url="{esc(ep.audio_url)}" '
                    f'length="{length or 0}" type="audio/mpeg"/>'
                )
                if ep.audio and ep.audio.get("duration"):
                    out.append(f"<itunes:duration>{ep.audio['duration']}</itunes:duration>")
        out.append("</item>")

    out += ["</channel>", "</rss>", ""]
    return "\n".join(out)


# ---------------------------------------------------------------------- main


def load_json(path: Path) -> dict[str, Any]:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def save_json(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=1, sort_keys=True, ensure_ascii=False) + "\n", encoding="utf-8")


def main() -> int:
    global FEED_BASE_URL
    if not FEED_BASE_URL:
        print("[warn] FEED_BASE_URL is unset; atom:link will point at example.invalid", file=sys.stderr)
    FEED_BASE_URL = FEED_BASE_URL or "https://example.invalid"

    session = make_session()

    index_urls = [f"{BASE}/playlists/{SHOW}"] + [f"{BASE}/playlists/{SHOW}{y}" for y in EXTRA_YEARS]
    episodes: dict[str, Episode] = {}
    for url in index_urls:
        html = fetch(session, url)
        if html is None:
            continue
        found = parse_index(html)
        print(f"[info] {url}: {len(found)} episodes")
        for ep in found:
            episodes.setdefault(ep.key, ep)
    if not episodes:
        print("[fatal] no episodes parsed; refusing to write an empty feed", file=sys.stderr)
        return 1

    ordered = sorted(episodes.values(), key=lambda e: e.date, reverse=True)[:MAX_ITEMS]

    tracklists = load_json(TRACKLIST_CACHE)
    audio_cache = load_json(AUDIO_CACHE)

    for position, ep in enumerate(ordered):
        if ep.playlist_id:
            cached = tracklists.get(ep.playlist_id)
            if cached is None or position < REFRESH_RECENT:
                html = fetch(session, ep.page_url)
                if html is not None:
                    songs = parse_show_page(html)
                    if songs or cached is None:
                        tracklists[ep.playlist_id] = songs
                    cached = tracklists.get(ep.playlist_id)
                    print(f"[info] {ep.playlist_id}: {len(cached or [])} tracks")
                time.sleep(0.25)
            if cached:
                ep.songs = cached

        if ep.archive_id:
            cached_audio = audio_cache.get(ep.archive_id)
            if cached_audio is None:
                cached_audio = resolve_audio(session, ep)
                if cached_audio and cached_audio["length"]:
                    audio_cache[ep.archive_id] = cached_audio
                    print(f"[info] audio {ep.archive_id}: {cached_audio['length']} bytes")
                time.sleep(0.25)
            ep.audio = cached_audio

    feed_path = ROOT / f"feed-{SHOW.lower()}.xml"
    podcast_path = ROOT / f"podcast-{SHOW.lower()}.xml"
    feed_path.write_text(build_feed(ordered, "playlist"), encoding="utf-8")
    podcast_path.write_text(build_feed(ordered, "podcast"), encoding="utf-8")

    # keep the cache from growing without bound
    keep = {ep.playlist_id for ep in ordered if ep.playlist_id}
    keep_audio = {ep.archive_id for ep in ordered if ep.archive_id}
    save_json(TRACKLIST_CACHE, {k: v for k, v in tracklists.items() if k in keep})
    save_json(AUDIO_CACHE, {k: v for k, v in audio_cache.items() if k in keep_audio})

    print(
        f"[done] wrote {feed_path.name} and {podcast_path.name}: "
        f"{len(ordered)} items, newest {ordered[0].date} "
        f"({sum(1 for e in ordered if e.songs)} with tracklists, "
        f"{sum(1 for e in ordered if e.audio)} with audio)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
